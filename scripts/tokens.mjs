// Compiles design/tokens.json (DTCG) into app/tokens.generated.css. `--check` fails if the CSS is stale.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
const t = JSON.parse(readFileSync(new URL("../design/tokens.json", import.meta.url)));
const out = [];
const walk = (node, path) => {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "$value" in v) {
      let val = v.$value;
      if (Array.isArray(val)) val = val.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
      else if (typeof val === "object") val = `${val.offsetX} ${val.offsetY} ${val.blur} ${val.spread} ${val.color}`;
      out.push(`  --${[...path, k].join("-")}: ${val};`);
    } else walk(v, [...path, k]);
  }
};
walk(t, []);
const css = `/* GENERATED by scripts/tokens.mjs from design/tokens.json. Do not edit. */\n:root {\n${out.join("\n")}\n}\n`;
const file = new URL("../app/tokens.generated.css", import.meta.url);
if (process.argv.includes("--check")) {
  if (!existsSync(file) || readFileSync(file, "utf8") !== css) { console.error("tokens.generated.css is stale: run npm run tokens"); process.exit(1); }
} else writeFileSync(file, css);
